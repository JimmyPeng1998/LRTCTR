%% Load the numerical results
scriptDir = fileparts(mfilename('fullpath'));
resultsDir = fullfile(scriptDir, 'Results');
if strcmp(getenv('LRTCTR_EXPS_LOCAL'),'1')
    resultName = 'Result_Exp2_scaling_local.mat';
else
    resultName = 'Result_Exp2_scaling.mat';
end
load(fullfile(resultsDir,resultName))

%% Plotting settings
colors = get(groot, 'defaultAxesColorOrder');
color_RCGQ = colors(1,:);
color_RCGE = colors(2,:);
color_RGDQ = colors(3,:);
color_RGDE = colors(4,:);
lwidth = 3;
msize = 10;
fontSize = 18;

figure('Position', [100 100 1500 480])
layout = tiledlayout(1, 3, 'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% Test error versus computational time
nexttile
plotRepeat = min(3, numel(resultsLarge));
h1 = semilogy(resultsLarge{plotRepeat}.duration_RGDE, ...
    resultsLarge{plotRepeat}.errorGamma_RGDE, '-x', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RGDE);
hold on
h2 = semilogy(resultsLarge{plotRepeat}.duration_RGDQ, ...
    resultsLarge{plotRepeat}.errorGamma_RGDQ, '-o', ...
    'MarkerSize', msize+4, 'LineWidth', lwidth, 'Color', color_RGDQ);
h3 = semilogy(resultsLarge{plotRepeat}.duration_RCGE, ...
    resultsLarge{plotRepeat}.errorGamma_RCGE, '->', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGE);
h4 = semilogy(resultsLarge{plotRepeat}.duration_RCGQ, ...
    resultsLarge{plotRepeat}.errorGamma_RCGQ, '-+', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGQ);
semilogy(resultsLarge{plotRepeat}.duration_RGDE, ...
    resultsLarge{plotRepeat}.errorGamma_RGDE, '-x', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RGDE, ...
    'HandleVisibility', 'off');
xlabel('Time (s)')
ylabel('Test error')
title(sprintf('$d=%d$, $n=%d$, $r=%d$', dLarge, nLarge, rLarge), ...
    'Interpreter', 'latex')
set(gca, 'FontSize', fontSize)
grid on

%% Time per iteration versus tensor order
nexttile
errorbar(dValues, mean(iterationTimeOrder_RGDE, 2), ...
    std(iterationTimeOrder_RGDE, 0, 2), '-x', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RGDE)
hold on
errorbar(dValues, mean(iterationTimeOrder_RGDQ, 2), ...
    std(iterationTimeOrder_RGDQ, 0, 2), '-o', ...
    'MarkerSize', msize+4, 'LineWidth', lwidth, 'Color', color_RGDQ)
errorbar(dValues, mean(iterationTimeOrder_RCGE, 2), ...
    std(iterationTimeOrder_RCGE, 0, 2), '->', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGE)
errorbar(dValues, mean(iterationTimeOrder_RCGQ, 2), ...
    std(iterationTimeOrder_RCGQ, 0, 2), '-+', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGQ)
xlabel('Tensor order $d$', 'Interpreter', 'latex')
ylabel('Time per iteration (s)')
title(sprintf('$n=%d$, $r=%d$', nOrder, rOrder), ...
    'Interpreter', 'latex')
set(gca, 'FontSize', fontSize, 'XTick', dValues)
grid on

%% Time per iteration versus TR rank
nexttile
errorbar(rValues, mean(iterationTimeRank_RGDE, 2), ...
    std(iterationTimeRank_RGDE, 0, 2), '-x', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RGDE)
hold on
errorbar(rValues, mean(iterationTimeRank_RGDQ, 2), ...
    std(iterationTimeRank_RGDQ, 0, 2), '-o', ...
    'MarkerSize', msize+4, 'LineWidth', lwidth, 'Color', color_RGDQ)
errorbar(rValues, mean(iterationTimeRank_RCGE, 2), ...
    std(iterationTimeRank_RCGE, 0, 2), '->', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGE)
errorbar(rValues, mean(iterationTimeRank_RCGQ, 2), ...
    std(iterationTimeRank_RCGQ, 0, 2), '-+', ...
    'MarkerSize', msize, 'LineWidth', lwidth, 'Color', color_RCGQ)
xlabel('TR rank $r$', 'Interpreter', 'latex')
ylabel('Time per iteration (s)')
title(sprintf('$d=%d$, $n=%d$', dRank, nRank), ...
    'Interpreter', 'latex')
set(gca, 'FontSize', fontSize, 'XTick', rValues)
grid on

hLegend = legend([h1 h2 h3 h4], ...
    'TR-RGD(E)', 'TR-RGD(Q)', 'TR-RCG(E)', 'TR-RCG(Q)', ...
    'Orientation', 'horizontal');
hLegend.Layout.Tile = 'north';
hLegend.ItemTokenSize = [30, 0.5];

set(gcf, 'Renderer', 'painters')
exportgraphics(layout, fullfile(resultsDir, 'Exp2_scaling.eps'), ...
    'ContentType', 'vector')

close all
